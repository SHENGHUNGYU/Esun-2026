"""Deterministic history provenance and explicit hold/gradual comparisons."""
import re
from .store import digest,encoded


def primary_proposal(pid):return not pid.startswith(('BASE_','ALT_'))


def alternative_id(pid):return 'ALT_'+digest(pid.encode())[:12]


def review_selection(action,values,evaluations,has_holdings):
    """Reject unsupported reasons; never claim factor scores cover trading costs."""
    # Evidence-bound holding/gradual reviews are mandatory for either decision.
    # Do not reject an entire selection just for a phrase about factor activity;
    # that biased repair feedback toward HOLD without evaluating the evidence.
    if re.search(r'(?:進場假說|失效條件)(?:現在)?\s*(?:[：:]|為|是|改為)',action.memory_review):raise ValueError('do_not_rewrite_history_only_comment_on_current_evidence')
    for comparison in action.comparisons:
        value=values.get(comparison.proposal_id,{})
        if value.get('proposal',{}).get('mode')=='gradual' and re.search(r'[0-9一二兩三四五六七八九十]+(?:檔|組)?換股|換股[0-9一二兩三四五六七八九十]+',comparison.reason):
            raise ValueError('gradual_adjusts_weights_not_stock_replacements')
    selected=values[action.selected_id]
    if not has_holdings or not selected.get('orders'):return
    if len(action.why_not_hold)<30:raise ValueError('explain_why_hold_is_insufficient')
    if selected['proposal']['mode'] not in {'gradual','risk_repair'}:
        aid=alternative_id(action.selected_id)
        if aid not in values:raise ValueError('same_factor_gradual_comparison_required')
        if len(action.why_not_gradual)<30:raise ValueError('explain_why_gradual_is_insufficient')
    if selected['proposal']['mode']!='risk_repair':
        mentioned=action.why_not_hold+' '+action.trade_justification
        if not security_mentions(mentioned,{o['ticker'] for o in selected['orders']}):
            raise ValueError('hold_comparison_requires_an_actual_traded_security')
    # All current comparisons and references are independently checked by the caller.
    # These explanations remain model judgments, not an expected-return certificate.


def history_audit(memory,selection,evaluation):
    """Copy historical entry reasons verbatim; model interpretation is separate."""
    if not memory:return {'entries':[],'model_comment':selection.get('memory_review',''),'note':'No frozen holding history.'}
    groups={}
    for h in memory['holdings']:
        t=h.get('entry_thesis')
        key=digest(encoded({k:t.get(k) for k in ['reason','invalidation','source_run','plan_sha256']})) if t else 'unknown'
        if key not in groups:
            groups[key]={'codes':[],'original_hypothesis':t['reason'] if t else None,
                'original_invalidation':t['invalidation'] if t else None,
                'source_run':t.get('source_run') if t else None,'plan_sha256':t.get('plan_sha256') if t else None,
                'historical_fact':'shares_reconciled_local_belief' if t else 'unknown',
                'submission_verified':False}
        groups[key]['codes'].append(h['code'])
    actions={o['ticker']:o['side'] for o in evaluation.get('orders',[])}
    return {'entries':list(groups.values()),'current_intentions':actions,
        'model_comment':selection.get('memory_review',''),
        'note':'Original text is copied from frozen history, not generated by the model. Current model comment is an interpretation; it cannot overwrite entry facts or certify thesis invalidation.'}


def history_text(audit):
    lines=[]
    for e in audit['entries']:
        lines.append('持股 '+','.join(e['codes'])+'；封存進場假說：'+(e['original_hypothesis'] or '未知')+'；封存失效條件：'+(e['original_invalidation'] or '未知'))
    return '\n'.join(lines) if lines else '尚無可核對的原始持股假說。'


def trade_observations(evaluation):
    ranked={r['code']:(i+1,r) for i,r in enumerate(evaluation.get('ranking',[]))}
    features=sorted({f['feature'] for f in evaluation['proposal']['factors']})
    rows=[]
    for order in evaluation.get('orders',[])[:6]:
        rank,row=ranked.get(order['ticker'],(None,{}))
        rows.append([order['ticker'],order['side'],rank,str(row['score']) if 'score' in row else None,
            *[row.get('research_features',{}).get(f) for f in features]])
    return {'columns':['code','side','rank','score',*features],'rows':rows,'omitted_orders':max(0,len(evaluation.get('orders',[]))-6),
        'note':'Actual frozen observations and deterministic ranks. Coverage is data availability, scores are not returns. Orders are not replacement counts.'}


def reported_submission(store,team_id,trade_date,cutoff):
    """Latest operator-reported submission, hash-bound and cutoff-aware."""
    from .operations import receipts,_scoped_rows
    from .contracts import instant
    rows=[r for r in receipts(store) if instant(r['at'])<=instant(cutoff)]
    scoped=_scoped_rows(store,rows,{'team_id':team_id})
    relevant=[r for r,day in scoped if day==str(trade_date) and r['event']['stage'] in {'submitted','submission_unknown'}]
    return relevant[-1] if relevant else None


def security_mentions(text,codes):
    """Recognize listed equity identifiers without accepting matching price numbers."""
    codes=set(codes)
    if not codes:return []
    one='(?:'+'|'.join(re.escape(c) for c in sorted(codes,key=len,reverse=True))+')'
    many=one+'(?:[、,，及與或 ]+'+one+')*'
    prefix=r'(?:個股|股票|代碼|(?:現行|現有)?持股中|新標的|買入(?:個股)?|賣出(?:個股)?|減碼|加碼|引入(?:新個股)?|如|trade_evidence(?:中)?顯示)\s*[（(]?'
    found=[]
    for match in re.finditer(prefix+'('+many+')',text):
        if re.match(r'(?:元|%|％|張|倍|股(?!價|票)|\.[0-9])',text[match.end(1):].lstrip()):continue
        found.append((match.start(1),match.end(1),match.group(1)))
    for match in re.finditer(r'(?<![0-9.])('+one+r')(?=(?:的)?(?:動能|外資|投信|營收|波動|排名|籌碼))',text):found.append((match.start(1),match.end(1),match.group(1)))
    for match in re.finditer(r'(?<![0-9.])('+many+r')(?=\s*(?:仍保留|的動能|五(?:日|與二十日)動能|二十日動能|動能|外資|投信|營收|籌碼))',text):
        found.append((match.start(1),match.end(1),match.group(1)))
    return found


def identifier_safe_text(text,codes):
    spans=security_mentions(text,codes)
    masked=list(text)
    for start,end,_ in spans:masked[start:end]=[' ']*(end-start)
    return ''.join(masked)


def check_review_attribution(action,reviews):
    """Bind claimed review labels to actual packets, without prescribing a trade."""
    verdicts={k:v['value']['verdict'] for k,v in reviews.items()}
    labels={'弱化':'weakened','支持':'supported','失效':'invalidated','未知':'unknown',
        'weakened':'weakened','supported':'supported','invalidated':'invalidated','unknown':'unknown'}
    texts=[(action.reason,None),(action.memory_review,None),(action.trade_justification,None),
           (action.why_not_hold,None),(action.why_not_gradual,None)]
    for c in action.comparisons:
        refs=getattr(c,'review_refs',[])
        if not set(refs)<=set(verdicts):raise ValueError('comparison_unknown_review_reference')
        if re.search(r'審查|被標記|判為|評為',c.reason) and not refs:raise ValueError('comparison_review_reference_required')
        if not re.search(r'[。！？]$',c.reason) or re.search(r'(?:邏輯|因此|所以|但是|且)[。！？]$',c.reason):raise ValueError('comparison_requires_complete_sentence')
        texts.append((c.reason,refs))
    for text,refs in texts:
        pattern=r'(?:被?標記為|判為|判定為|評為|審查結論為)\s*[（(]?(弱化|支持|失效|未知|weakened|supported|invalidated|unknown)'
        for m in re.finditer(pattern,text):
            codes=re.findall(r'個股\s*(\d{4,6})(?!\d)',text[max(0,m.start()-90):m.start()])
            if not codes:continue
            key='H'+codes[-1]
            if key not in verdicts:raise ValueError('claimed_review_does_not_exist:'+key)
            if refs is not None and key not in refs:raise ValueError('claimed_security_requires_own_review_ref:'+key)
            if verdicts[key]!=labels[m.group(1)]:raise ValueError('claimed_review_verdict_mismatch:'+key)
